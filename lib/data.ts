export function getIndustry(slug: string) {
  return industries.find((i) => i.slug === slug);
}
export function getProfessions(industrySlug: string) {
  return professions.filter((p) => p.industry === industrySlug);
}
export function getProfession(industrySlug: string, slug: string) {
  return professions.find((p) => p.industry === industrySlug && p.slug === slug);
}

